import type { ResolvedConfig } from './config'
import { randomBytes } from 'node:crypto'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'
import { stringify } from 'yaml'
import { buildStack, envFilePath } from './compose'
import { formatEnvFile, readEnvFile, resolveSource } from './secrets'

export interface Generated {
  /** The `.dev-container` directory. */
  dir: string
  composeFile: string
}

export interface GenerateOptions {
  config: ResolvedConfig
  root: string
  /** Defaults to `process.env`. */
  env?: NodeJS.ProcessEnv
}

/**
 * Writes `.dev-container/`: the compose file, broker rules and env files with
 * resolved secrets. Placeholders are regenerated on every run.
 */
export function generate({ config, root, env = process.env }: GenerateOptions): Generated {
  const dir = join(root, '.dev-container')
  const envFiles = resolveEnvFiles(config, { root, env, envFile: config.envFile ? readEnvFile(resolve(root, config.envFile)) : {} })

  mkdirSync(join(dir, 'env'), { recursive: true })
  writeFileSync(join(dir, '.gitignore'), '*\n')

  const stack = buildStack(config, {
    root,
    dir,
    assets: fileURLToPath(new URL('..', import.meta.url)),
    placeholders: Object.fromEntries(config.secrets.map(s => [s.env, `dc-${s.env}-${randomBytes(8).toString('hex')}`])),
    controlToken: readControlToken(dir),
  })

  for (const [name, values] of Object.entries(envFiles))
    writeFileSync(envFilePath(dir, name), formatEnvFile(values), { mode: 0o600 })
  for (const path of stack.persistDirs)
    mkdirSync(path, { recursive: true })
  writeFileSync(join(dir, 'rules.json'), `${JSON.stringify(stack.rules, null, 2)}\n`)
  if (stack.tailscaleServe)
    writeFileSync(join(dir, 'tailscale-serve.json'), `${JSON.stringify(stack.tailscaleServe, null, 2)}\n`)
  const composeFile = join(dir, 'compose.yml')
  writeFileSync(composeFile, `# Generated by dev-container; edits are overwritten.\n${stringify(stack.compose, { lineWidth: 0 })}`)

  return { dir, composeFile }
}

/** Reads the control token, creating it on first use. It stays stable across runs. */
export function readControlToken(dir: string): string {
  const path = join(dir, 'control-token')
  if (existsSync(path))
    return readFileSync(path, 'utf8').trim()
  mkdirSync(dir, { recursive: true })
  const token = randomBytes(24).toString('base64url')
  writeFileSync(path, `${token}\n`, { mode: 0o600 })
  return token
}

/** Resolves every secret up front so a missing one fails before anything is written. */
function resolveEnvFiles(config: ResolvedConfig, lookup: Parameters<typeof resolveSource>[1]): Record<string, Record<string, string>> {
  const errors: string[] = []
  const attempt = (label: string, run: () => string): string => {
    try {
      return run()
    }
    catch (error) {
      errors.push(`${label}: ${error instanceof Error ? error.message : String(error)}`)
      return ''
    }
  }

  const files: Record<string, Record<string, string>> = {
    broker: Object.fromEntries(config.secrets.map(secret => [
      `DEV_CONTAINER_SECRET_${secret.env}`,
      attempt(`secret ${secret.env}`, () => resolveSource(secret.from ?? { env: secret.env }, lookup)),
    ])),
  }
  if (config.tailscale) {
    const { authKey } = config.tailscale
    files.tailscale = { TS_AUTHKEY: attempt('tailscale.authKey', () => resolveSource(authKey, lookup)) }
  }
  for (const [name, service] of Object.entries(config.services)) {
    const refs = Object.entries(service.env).flatMap(([key, value]) => typeof value === 'string' ? [] : [[key, value] as const])
    if (refs.length)
      files[name] = Object.fromEntries(refs.map(([key, source]) => [key, attempt(`services.${name}.env.${key}`, () => resolveSource(source, lookup))]))
  }

  if (errors.length)
    throw new Error(`Could not resolve secrets:\n${errors.map(e => `  - ${e}`).join('\n')}`)
  return files
}
