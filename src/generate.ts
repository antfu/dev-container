import type { BuiltinName } from './builtins'
import type { ResolvedConfig, ResolvedSecret, SecretSourceConfig } from './config'
import type { SecretLookup } from './secrets'
import { randomBytes } from 'node:crypto'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'
import { Diagnostic } from 'nostics'
import { stringify } from 'yaml'
import { BUILTIN_NAMES, BUILTINS } from './builtins'
import { buildStack, envFilePath, serveFilePath } from './compose'
import { tailscaleNodes } from './config'
import { diagnostics } from './diagnostics'
import { formatEnvFile, lookupEnv, readEnvFile, resolveSource } from './secrets'

const ENV_NAME = /^[A-Z_]\w*$/i

export interface Generated {
  /** The `.dev-container` directory. */
  dir: string
  composeFile: string
  /** Non-fatal findings, such as a builtin secret that is off because its token is unset. */
  warnings: Diagnostic<unknown>[]
}

export interface GenerateOptions {
  config: ResolvedConfig
  root: string
  /** Defaults to `process.env`. */
  env?: NodeJS.ProcessEnv
}

/** Merges the listed dotenv files, which must exist; without a list, the default one is read only if present. */
function readEnvFiles(root: string, files: string[] | undefined, fallback: string): Record<string, string> {
  const list = files ?? [fallback].filter(file => existsSync(resolve(root, file)))
  return Object.assign({}, ...list.map(file => readEnvFile(resolve(root, file))))
}

/** Where `{ env }` sources are looked up: the host environment, then the env files. */
export function createLookup({ config, root, env = process.env }: GenerateOptions): SecretLookup {
  return { root, env, envFile: { ...readEnvFiles(root, config.envFile, '.env'), ...readEnvFiles(root, config.envSecretFile, '.env.secret') } }
}

/**
 * Writes `.dev-container/`: the compose file and env files with
 * resolved secrets. Placeholders are regenerated on every run.
 */
export function generate({ config: userConfig, root, env = process.env }: GenerateOptions): Generated {
  const dir = join(root, '.dev-container')
  const secretFile = readEnvFiles(root, userConfig.envSecretFile, '.env.secret')
  const lookup = { root, env, envFile: { ...readEnvFiles(root, userConfig.envFile, '.env'), ...secretFile } }
  const warnings: Diagnostic<unknown>[] = []
  const config = { ...userConfig, secrets: activeSecrets(userConfig, lookup, warnings, Object.keys(secretFile)) }
  const envFiles = resolveEnvFiles(config, lookup)

  mkdirSync(join(dir, 'env'), { recursive: true })
  writeFileSync(join(dir, '.gitignore'), '*\n')

  const stack = buildStack(config, {
    root,
    dir,
    assets: fileURLToPath(new URL('..', import.meta.url)),
    placeholders: Object.fromEntries(config.secrets.map(s => [s.env, `dc-${s.env}-${randomBytes(8).toString('hex')}`])),
    dashboardToken: readDashboardToken(dir, config.dashboard.token, env),
  })

  for (const [name, values] of Object.entries(envFiles))
    writeFileSync(envFilePath(dir, name), formatEnvFile(values), { mode: 0o600 })
  for (const path of stack.persistDirs)
    mkdirSync(path, { recursive: true })
  for (const [node, serve] of Object.entries(stack.tailscaleServe))
    writeFileSync(serveFilePath(dir, node), `${JSON.stringify(serve, null, 2)}\n`)
  const composeFile = join(dir, 'compose.yml')
  writeFileSync(composeFile, `# Generated by dev-container; edits are overwritten.\n${stringify(stack.compose, { lineWidth: 0, aliasDuplicateObjects: false })}`)

  return { dir, composeFile, warnings }
}

/**
 * The dashboard token: `$DEV_CONTAINER_DASHBOARD_TOKEN` on the host when set, else `dashboard.token` from the
 * config, else `dashboard-token` in the stack directory, created on first use. It stays stable across runs.
 */
export function readDashboardToken(dir: string, configured?: string, env: NodeJS.ProcessEnv = process.env): string {
  const chosen = env.DEV_CONTAINER_DASHBOARD_TOKEN?.trim() || configured
  if (chosen)
    return chosen
  const path = join(dir, 'dashboard-token')
  if (existsSync(path))
    return readFileSync(path, 'utf8').trim()
  mkdirSync(dir, { recursive: true })
  const token = randomBytes(24).toString('base64url')
  writeFileSync(path, `${token}\n`, { mode: 0o600 })
  return token
}

/**
 * Enabled builtins, the configured secrets, then every other `envSecretFile` variable bound to no host;
 * no two may claim the same variable.
 */
function activeSecrets(config: ResolvedConfig, lookup: SecretLookup, warnings: Diagnostic<unknown>[], fileVars: string[]): ResolvedSecret[] {
  const claimed: { secret: ResolvedSecret, builtin?: BuiltinName }[] = []
  for (const builtin of BUILTIN_NAMES) {
    const setting = config.builtins[builtin]
    const { secret, detect } = BUILTINS[builtin]
    if (setting === false)
      continue
    const found = detect.find(name => lookupEnv(lookup, name))
    const from = setting?.from ?? (found && { env: found })
    if (from)
      claimed.push({ builtin, secret: { ...secret, from, rules: setting?.rules ?? secret.rules } })
    else
      warnings.push(diagnostics.DEV_CONTAINER_S2002({ builtin, envs: detect }))
  }
  claimed.push(...config.secrets.map(secret => ({ secret })))

  const owners = new Map<string, BuiltinName | undefined>()
  for (const { secret, builtin } of claimed) {
    for (const env of [secret.env, ...secret.aliases]) {
      if (owners.has(env))
        throw diagnostics.DEV_CONTAINER_C1003({ env, builtin: owners.get(env) ?? builtin })
      owners.set(env, builtin)
    }
  }
  const read = envsRead(config)
  const unbound = fileVars.filter(env => !owners.has(env) && !read.has(env) && ENV_NAME.test(env))
    .map((env): ResolvedSecret => ({ env, aliases: [], hosts: [], rules: [] }))
  return [...claimed.map(({ secret }) => secret), ...unbound]
}

/** The `gpg` builtin's key sources; an unset default one is simply off. */
export function gpgSources(config: ResolvedConfig): { privateKey: SecretSourceConfig, publicKey: SecretSourceConfig } | undefined {
  const setting = config.builtins.gpg
  if (!setting)
    return undefined
  const given = setting === 'auto' ? {} : setting
  return { privateKey: given.privateKey ?? { env: 'GPG_PRIVATE_KEY' }, publicKey: given.publicKey ?? { env: 'GPG_PUBLIC_KEY' } }
}

/** Variables that some `{ env }` source reads itself, so they must not also become placeholders. */
function envsRead(config: ResolvedConfig): Set<string> {
  const sources: SecretSourceConfig[] = [
    ...tailscaleNodes(config).map(node => node.authKey),
    ...config.secrets.flatMap(secret => secret.from ? [secret.from] : []),
    ...BUILTIN_NAMES.flatMap((name) => {
      const builtin = config.builtins[name]
      return builtin && builtin.from ? [builtin.from] : []
    }),
    ...Object.values(gpgSources(config) ?? {}),
    ...Object.values(config.services).flatMap(service => Object.values(service.env).filter(value => typeof value !== 'string')),
  ]
  return new Set(sources.flatMap(source => 'env' in source ? [source.env] : []))
}

/** Resolves every secret up front so all missing ones are reported before anything is written. */
function resolveEnvFiles(config: ResolvedConfig, lookup: SecretLookup): Record<string, Record<string, string>> {
  const failures: Diagnostic<unknown>[] = []
  const attempt = (source: SecretSourceConfig, label: string): string => {
    try {
      return resolveSource(source, lookup, label)
    }
    catch (error) {
      if (!(error instanceof Diagnostic))
        throw error
      failures.push(error)
      return ''
    }
  }

  const files: Record<string, Record<string, string>> = {
    broker: Object.fromEntries(config.secrets.map(secret => [
      `DEV_CONTAINER_SECRET_${secret.env}`,
      attempt(secret.from ?? { env: secret.env }, `secret ${secret.env}`),
    ])),
  }
  for (const node of tailscaleNodes(config))
    files[node.name] = { TS_AUTHKEY: attempt(node.authKey, `${node.label}.authKey`) }
  for (const [name, service] of Object.entries(config.services)) {
    const refs = Object.entries(service.env).flatMap(([key, value]) => typeof value === 'string' ? [] : [[key, value] as const])
    // The file is written even when every reference is optional and unset, since compose requires it.
    if (refs.length) {
      files[name] = Object.fromEntries(refs.flatMap(([key, source]) =>
        'optional' in source && source.optional && 'env' in source && !lookupEnv(lookup, source.env)
          ? []
          : [[key, attempt(source, `services.${name}.env.${key}`)]]))
    }
  }

  if (failures.length)
    throw new AggregateError(failures, 'Could not resolve secrets')
  return files
}
